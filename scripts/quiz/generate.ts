/**
 * pnpm quiz:generate
 *
 * Runs the generators and writes quiz/bank/generated/*.yml. Deterministic: the same content/ and
 * catalogues give byte-identical files. Ids are kept between runs (quiz/DESIGN.md section 6):
 * a question is matched to its old self by generator, ref, page, anchor and block.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parse } from 'yaml'
import { BankFileSchema, type Question } from '../../quiz/schema.ts'
import { hash53 } from '../../quiz/lib/select.ts'
import { readAllPages } from './lib/docs.ts'
import { BANK_DIR, fingerprint, loadLineTargets, loadLock, loadMistakes, rel, toYaml } from './lib/bank.ts'
import { generateSpotTheMistake } from './generators/spot-the-mistake.ts'
import { generatePickTheLine } from './generators/pick-the-line.ts'
import { generateGlossary } from './generators/glossary.ts'
import type { GeneratedDraft } from './generators/common.ts'

const HEADER = `
# GENERATED by \`pnpm quiz:generate\` from quiz/catalogue/%CATALOGUE% and the code blocks in content/.
# Review the diff in your pull request. To change a question, change the catalogue entry or the docs,
# then generate again. Ids are kept between runs; a question that no longer applies is retired, not removed.
# You may add \`reviewed\`, \`author\`, \`difficulty\` and \`exposure\` by hand: generating again keeps them.
`

/** Fields a person may add to a generated question; generating again keeps them. */
const KEPT = ['author', 'reviewed', 'difficulty', 'calibration', 'exposure', 'cutRating'] as const

type Kind = { file: string, catalogue: string, prefix: string, idPart: (d: GeneratedDraft) => string, drafts: GeneratedDraft[] }

function matchKey(name: string, ref: string, page: string, anchor: string, block: number) {
  return `${name}|${ref}|${page}|${anchor}|${block}`
}

function keyOf(q: Question): string {
  // The source the code came from: the one with a block (code questions), else the first.
  const s = q.sources.find(x => x.kind === 'docs' && x.block !== undefined) ?? q.sources[0]
  return s.kind === 'docs' ? matchKey(q.generator!.name, q.generator!.ref, s.page, s.anchor, s.block ?? -1) : ''
}

/** The short, stable code a glossary family uses, so neither the family nor the id names the term. */
export function termCode(anchor: string): string {
  return hash53(`term|${anchor}`).toString(36).slice(0, 6)
}

async function main() {
  const pages = await readAllPages()
  const lock = loadLock()
  const kinds: Kind[] = [
    { file: 'spot-the-mistake.yml', catalogue: 'mistakes.yml', prefix: 'gen.mistake', idPart: d => d.ref, drafts: generateSpotTheMistake(loadMistakes(), pages) },
    { file: 'pick-the-line.yml', catalogue: 'line-targets.yml', prefix: 'gen.target', idPart: d => d.ref, drafts: generatePickTheLine(loadLineTargets(), pages) },
    {
      file: 'glossary.yml',
      catalogue: 'glossary.yml',
      prefix: 'gen.term',
      // The id names the glossary group, never the term (the term is the answer).
      idPart: (d) => {
        const page = pages.get(d.page)!
        const term = page.sections.find(s => s.anchor === d.anchor)!
        return page.sections.filter(s => s.depth === 2 && s.start < term.start && s.end >= term.end).at(-1)!.anchor
      },
      // A family set in the catalogue (shared with a hand-written question) is kept.
      drafts: generateGlossary(pages).map(d => ({ ...d, question: { ...d.question, family: d.question.family?.startsWith('term:') ? `term:${termCode(d.anchor)}` : d.question.family } }))
    }
  ]

  for (const kind of kinds) {
    const path = join(BANK_DIR, 'generated', kind.file)
    const old: Question[] = existsSync(path) ? BankFileSchema.parse(parse(readFileSync(path, 'utf8'))).questions : []
    const usedIds = new Set([...old.map(q => q.id), ...Object.keys(lock.questions)])
    const oldByKey = new Map(old.filter(q => q.status !== 'retired').map(q => [keyOf(q), q]))
    const matched = new Set<Question>()
    const out: Question[] = []
    let kept = 0
    let bumped = 0
    let added = 0

    for (const draft of kind.drafts) {
      const prev = oldByKey.get(matchKey(draft.question.generator!.name, draft.ref, draft.page, draft.anchor, draft.block))
      let q: Question
      if (prev && !matched.has(prev)) {
        matched.add(prev)
        q = { id: prev.id, version: prev.version, status: prev.status, ...draft.question } as Question
        for (const field of KEPT) if (prev[field] !== undefined) (q as Record<string, unknown>)[field] = prev[field]
        if (fingerprint(q) !== fingerprint(prev)) {
          q.version = prev.version + 1
          bumped++
        } else {
          kept++
        }
      } else {
        const base = `${kind.prefix}.${kind.idPart(draft)}`
        let n = 1
        while (usedIds.has(`${base}.${n}`)) n++
        usedIds.add(`${base}.${n}`)
        q = { id: `${base}.${n}`, version: 1, status: 'live', ...draft.question } as Question
        added++
      }
      out.push(q)
    }

    let retired = 0
    for (const q of old) {
      if (q.status === 'retired') {
        out.push(q)
      } else if (!matched.has(q)) {
        out.push({ ...q, status: 'retired', retired: { reason: 'stale-source: the source block is gone or no longer matches the catalogue entry' } })
        retired++
      }
    }

    // Validate before writing: the pipeline guarantees every file it writes passes BankFileSchema.
    const checked = BankFileSchema.safeParse({ questions: out })
    if (!checked.success) {
      for (const issue of checked.error.issues) console.error(`${kind.file}: ${issue.path.join('.')}: ${issue.message}`)
      process.exitCode = 1
      continue
    }
    writeFileSync(path, toYaml(HEADER.replace('%CATALOGUE%', kind.catalogue), out))
    console.log(`${rel(path)}: ${out.length} questions (${kept} kept, ${bumped} new versions, ${added} added, ${retired} retired)`)
  }
}

await main()
